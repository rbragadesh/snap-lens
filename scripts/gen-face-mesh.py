"""Generate src/engine/faceMeshData.ts from MediaPipe's canonical_face_model.obj.

Usage: python3 scripts/gen-face-mesh.py path/to/canonical_face_model.obj
Source: google-ai-edge/mediapipe mediapipe/modules/face_geometry/data/canonical_face_model.obj (Apache-2.0)
"""
import sys

path = sys.argv[1]
vts, faces = [], []
nverts = 0
for line in open(path):
    p = line.split()
    if not p:
        continue
    if p[0] == 'v':
        nverts += 1
    elif p[0] == 'vt':
        vts.append((float(p[1]), float(p[2])))
    elif p[0] == 'f':
        faces.append([tuple(int(i) - 1 for i in c.split('/')[:2]) for c in p[1:]])

uv = [None] * nverts
for f in faces:
    for v, t in f:
        if uv[v] is not None and uv[v] != vts[t]:
            raise SystemExit(f'vertex {v} maps to two uvs')
        uv[v] = vts[t]
assert all(u is not None for u in uv)

# Store UVs with y pointing down (image convention): y = 1 - v.
uvs = [c for u, v in uv for c in (round(u, 5), round(1 - v, 5))]

# Make every triangle counter-clockwise when viewed in image space (y down),
# i.e. signed area < 0 with the usual formula, so culling can drop back-facing triangles.
tris = []
for f in faces:
    a, b, c = (v for v, _ in f)
    (ax, ay), (bx, by), (cx, cy) = ((uvs[2*i], uvs[2*i+1]) for i in (a, b, c))
    area = (bx - ax) * (cy - ay) - (cx - ax) * (by - ay)
    tris.extend((a, b, c) if area < 0 else (a, c, b))

out = sys.argv[2] if len(sys.argv) > 2 else 'src/engine/faceMeshData.ts'
with open(out, 'w') as fh:
    fh.write('// Generated by scripts/gen-face-mesh.py from MediaPipe canonical_face_model.obj (Apache-2.0).\n')
    fh.write('// UVs are in image convention (y down). Triangles are wound consistently in that space.\n')
    fh.write(f'export const FACE_UVS = new Float32Array([{",".join(map(str, uvs))}]);\n')
    fh.write(f'export const FACE_TRIANGLES = new Uint16Array([{",".join(map(str, tris))}]);\n')
print('verts', nverts, 'tris', len(tris) // 3, 'uv10', uv[10], 'uv152', uv[152])
